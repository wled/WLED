/*
 * FS Sync usermod (ESP32 only - packet authentication uses mbedtls)
 *
 * Synchronizes image files (.gif, .bmp) on the WLED file system (LittleFS)
 * between all instances that share a sync group, over UDP (default port 21325).
 *
 * How it works:
 * - Each instance periodically scans its file system and builds a manifest
 *   (path, size, modification time and CRC32 of every image file).
 * - The manifest checksum is announced to the subnet broadcast address.
 *   Announcements carry the sender's sync groups and are only accepted by
 *   instances whose receive groups intersect - the same semantics as the
 *   built-in WLED state sync (see udp.cpp).
 * - An instance seeing a different manifest requests the full manifest,
 *   diffs it against its local file system and pulls every file that is
 *   missing locally or older than the remote copy. The newest modification
 *   time wins; ties are broken by the higher unit ID (last IP octet), so both
 *   sides always agree on the winner.
 * - Files are transferred in ~1300 byte UDP chunks, written to "<path>.part"
 *   and renamed over the target once size and CRC32 are verified. The FS API
 *   cannot set a file's modification time, so the winning mtime of a received
 *   file is recorded in a small local sidecar file (/fssync.meta) and reused
 *   while the file is unchanged; this keeps manifests identical across
 *   instances that synced the same file.
 *
 * Only image files (.gif, .bmp) are synced. The "Image" effect can display
 * lowercase .gif files only (see image_loader.cpp); .bmp files are synced as
 * plain file distribution. Everything else on the file system is
 * left alone: the device configuration (cfg.json), security settings
 * (wsec.json, which holds the WiFi passwords), presets, WLED backup files
 * (/bkp.*) and temporary files are never sent or received.
 * File deletions are not propagated.
 *
 * Security: file transfers require a shared passphrase (set in the usermod
 * settings, or at compile time via -D USERMOD_FS_SYNC_PASSPHRASE='"..."').
 * When a passphrase is set, every packet carries a unix timestamp and a
 * truncated HMAC-SHA256 tag (keyed by the passphrase) over header, payload
 * and timestamp; the timestamp bounds replay (needs a synced clock, i.e.
 * NTP, on both sides). Without a passphrase, instances only discover each
 * other - no files are transferred in either direction. While the OTA lock
 * is enabled, incoming file writes are rejected. This is still a LAN
 * protocol without TLS: the passphrase is a shared secret, so it only keeps
 * out peers that do not know it (dictionary attacks apply).
 */
