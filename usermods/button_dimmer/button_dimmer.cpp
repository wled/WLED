#include "wled.h"

/*
 * Button Dimmer usermod
 *
 * Turns one WLED push button into a wall-dimmer style control:
 *  - 1..N clicks : a configurable action per click count (toggle, full brightness, preset, colour, ...)
 *  - hold        : smooth brightness ramp that turns around at both ends, or a one-shot action
 *
 * Everything is configured on the usermod settings page. The page has three levels (easy, medium,
 * expert) that only change which settings are shown.
 *
 * The usermod takes over the selected button completely, so the stock actions of that button
 * (button presets, hold 5 s for AP mode, hold 10 s for factory reset, MQTT button events) are not available.
 */

// AI: below section was generated by an AI

#ifndef BUTTON_DIMMER_MAX_CLICKS
  #define BUTTON_DIMMER_MAX_CLICKS 4   // highest click count that can get its own action
#endif

class ButtonDimmer : public Usermod {
  private:
    // the order must match the option list in appendConfigData()
    enum Action : uint8_t {
      ACT_NONE = 0,
      ACT_TOGGLE,
      ACT_ON,
      ACT_OFF,
      ACT_FULL,     // go to the upper brightness limit
      ACT_BRI,      // value = brightness 1-255
      ACT_PRESET,   // value = preset ID
      ACT_COLOR,    // value = 0xWWRRGGBB
      ACT_RANDOM,   // random primary colour
      ACT_DIM,      // hold only: ramp brightness while held
      ACT_COUNT
    };

    struct Slot {
      uint8_t  action;
      uint32_t value;
    };

    // settings
    bool     enabled     = true;
    uint8_t  btn         = 0;      // WLED button index
    uint8_t  level       = 0;      // settings page level: 0 easy, 1 medium, 2 expert (UI only)
    Slot     clickSlot[BUTTON_DIMMER_MAX_CLICKS];
    Slot     holdSlot    = {ACT_DIM, 0};
    uint8_t  minBri      = 3;      // lower end of the ramp
    uint8_t  maxBri      = 255;    // upper end of the ramp, also used by "full brightness"
    bool     turnAround  = true;   // keep ramping in the other direction when an end is reached
    uint16_t debounceMs  = 50;     // shorter presses are ignored
    uint16_t holdMs      = 400;    // a press longer than this is a hold
    uint16_t clickGapMs  = 300;    // longest pause between the clicks of a multi-click
    uint16_t stepMs      = 25;     // ramp interval
    uint8_t  stepSize    = 3;      // brightness change per ramp step
    uint16_t endPauseMs  = 500;    // rest at an end before turning around
    bool     syncDimming = false;  // send sync notifications on every ramp step instead of once at the end

    // state
    bool     pressed  = false;
    bool     holding  = false;
    bool     dimming  = false;
    bool     dirUp    = true;
    uint8_t  clicks   = 0;         // clicks counted so far
    uint8_t  maxClicks = 0;        // highest click count that has an action
    uint16_t stepWait = 0;
    unsigned long tDown = 0, tUp = 0, tStep = 0;

    static const char _name[];

    static bool needsValue(uint8_t a) { return a == ACT_BRI || a == ACT_PRESET || a == ACT_COLOR; }

    // apply the brightness without fading: a fade restarted on every ramp step would lag behind
    void applyNow(byte callMode) {
      // stateUpdated() with a zero duration cancels a one-shot transition (JSON "tt", playlist) and clears its flag,
      // so its temporary duration must not be put back: return to the normal one instead
      const uint16_t t = jsonTransitionOnce ? transitionDelay : strip.getTransition();
      strip.setTransition(0);
      stateUpdated(callMode);
      strip.setTransition(t);
    }

    void setBri(uint8_t b) {
      bri = b;
      stateChanged = true;
      stateUpdated(CALL_MODE_BUTTON);
    }

    void doAction(const Slot& s) {
      switch (s.action) {
        case ACT_TOGGLE: toggleOnOff(); stateUpdated(CALL_MODE_BUTTON); break;
        case ACT_ON:     if (bri == 0) { toggleOnOff(); stateUpdated(CALL_MODE_BUTTON); } break;
        case ACT_OFF:    if (bri != 0) { toggleOnOff(); stateUpdated(CALL_MODE_BUTTON); } break;
        case ACT_FULL:   setBri(maxBri); break;
        case ACT_BRI:    setBri(constrain(s.value, 1, 255)); break;
        case ACT_PRESET: if (s.value > 0) applyPreset(s.value, CALL_MODE_BUTTON_PRESET); break;
        case ACT_COLOR:
          colPri[0] = R(s.value); colPri[1] = G(s.value); colPri[2] = B(s.value); colPri[3] = W(s.value);
          if (bri == 0) toggleOnOff();
          colorUpdated(CALL_MODE_BUTTON);
          break;
        case ACT_RANDOM:
          setRandomColor(colPri);
          if (bri == 0) toggleOnOff();
          colorUpdated(CALL_MODE_BUTTON);
          break;
        default: break;
      }
    }

    // run the action for the number of clicks counted so far
    void fireClicks() {
      const uint8_t n = clicks;
      clicks = 0;
      if (n > 0 && n <= BUTTON_DIMMER_MAX_CLICKS) doAction(clickSlot[n-1]);
    }

    void startHold(unsigned long now) {
      holding = true;
      fireClicks(); // click(s) followed by a hold: the clicks still count
      if (holdSlot.action != ACT_DIM) {
        doAction(holdSlot);
        return;
      }
      dimming = true;
      if (bri == 0)            { bri = minBri; dirUp = true; } // from off: start at the bottom
      else if (bri >= maxBri)  dirUp = false;
      else if (bri <= minBri)  dirUp = true;
      else                     dirUp = !dirUp;                 // alternate like a wall dimmer
      tStep = now;
      stepWait = stepMs;
      applyNow(syncDimming ? CALL_MODE_BUTTON : CALL_MODE_NO_NOTIFY);
    }

    void dimStep(unsigned long now) {
      tStep = now;
      stepWait = stepMs;
      int nb = bri + (dirUp ? stepSize : -stepSize);
      if (dirUp && nb >= maxBri) {
        nb = maxBri;
        if (turnAround) { dirUp = false; stepWait = endPauseMs; }
      } else if (!dirUp && nb <= minBri) {
        nb = minBri;
        if (turnAround) { dirUp = true; stepWait = endPauseMs; }
      }
      if (nb == bri) return;
      bri = nb;
      applyNow(syncDimming ? CALL_MODE_BUTTON : CALL_MODE_NO_NOTIFY);
    }

    void stopHold() {
      holding = false;
      if (!dimming) return;
      dimming = false;
      stateChanged = true; // publish the final level once (sync, MQTT, UI)
      applyNow(CALL_MODE_BUTTON);
    }

    void slotToJson(JsonObject parent, const String& key, const Slot& s) {
      JsonObject o = parent.createNestedObject(key);
      char buf[12] = "";
      if (s.action == ACT_COLOR) {
        if (W(s.value)) snprintf_P(buf, sizeof(buf), PSTR("%02x%02x%02x%02x"), R(s.value), G(s.value), B(s.value), W(s.value));
        else            snprintf_P(buf, sizeof(buf), PSTR("%02x%02x%02x"), R(s.value), G(s.value), B(s.value));
      } else if (needsValue(s.action)) {
        snprintf_P(buf, sizeof(buf), PSTR("%u"), (unsigned)s.value);
      }
      o[F("action")] = s.action;
      o[F("value")]  = String(buf); // always a string, so the settings page renders a text field
    }

    bool slotFromJson(JsonObject parent, const String& key, Slot& s, bool isHold) {
      JsonObject o = parent[key];
      if (o.isNull()) return false;
      uint8_t a = o[F("action")] | s.action;
      if (a >= ACT_COUNT || (a == ACT_DIM && !isHold)) a = ACT_NONE;
      String v = o[F("value")].as<String>();
      v.trim();
      if (v.startsWith("#")) v.remove(0, 1);
      s.action = a;
      if (a == ACT_COLOR) {
        byte c[4] = {255, 255, 255, 0}; // white if the text is not a valid RRGGBB / RRGGBBWW colour
        colorFromHexString(c, v.c_str());
        s.value = RGBW32(c[0], c[1], c[2], c[3]);
      } else {
        s.value = constrain(v.toInt(), 0, 255);
      }
      return true;
    }

    static String clickKey(unsigned n) { return String(F("click-")) + String(n); }

  public:
    ButtonDimmer() {
      for (auto &s : clickSlot) s = {ACT_NONE, 0};
      clickSlot[0].action = ACT_TOGGLE;
      #if BUTTON_DIMMER_MAX_CLICKS > 1
      clickSlot[1].action = ACT_FULL;
      #endif
      maxClicks = min(2, BUTTON_DIMMER_MAX_CLICKS);
    }

    void setup() override {}
    void loop() override {}

    bool handleButton(uint8_t b) override {
      if (!enabled || b != btn) return false;
      const uint8_t type = buttons[b].type;
      if (type != BTN_TYPE_PUSH && type != BTN_TYPE_PUSH_ACT_HIGH && type != BTN_TYPE_TOUCH) return false; // momentary buttons only

      const unsigned long now = millis();
      const bool down = isButtonPressed(b);

      if (down) {
        if (!pressed) {                                   // press started
          if (clicks > 0 && now - tUp >= clickGapMs) fireClicks(); // the earlier clicks timed out without an idle call in between
          pressed = true;
          holding = false;
          tDown = now;
        } else if (!holding) {
          if (now - tDown > holdMs) startHold(now);       // hold begins
        } else if (dimming && now - tStep >= stepWait) {
          dimStep(now);
        }
      } else if (pressed) {                               // released
        pressed = false;
        if (!holding && now - tDown > holdMs) startHold(now); // long press whose hold start was never seen: still a hold
        if (holding) {
          stopHold();
        } else if (now - tDown > debounceMs) {            // a valid click
          clicks++;
          tUp = now;
          if (clicks >= maxClicks) fireClicks();          // no higher click count is configured: no need to wait
        }
      } else if (clicks > 0 && now - tUp >= clickGapMs) { // idle: no further click came
        fireClicks();
      }
      return true; // suppress the default button handling
    }

    void addToConfig(JsonObject& root) override {
      JsonObject top = root.createNestedObject(FPSTR(_name));
      top[F("enabled")] = enabled;
      top[F("button")]  = btn;
      top[F("level")]   = level;
      for (unsigned i = 0; i < BUTTON_DIMMER_MAX_CLICKS; i++) slotToJson(top, clickKey(i+1), clickSlot[i]);
      slotToJson(top, F("hold"), holdSlot);
      JsonObject dim = top.createNestedObject(F("dimming"));
      dim[F("min-brightness")] = minBri;
      dim[F("max-brightness")] = maxBri;
      dim[F("turn-around")]    = turnAround;
      JsonObject adv = top.createNestedObject(F("advanced"));
      adv[F("debounce")]           = debounceMs;
      adv[F("hold-time")]          = holdMs;
      adv[F("multi-click-gap")]    = clickGapMs;
      adv[F("step-interval")]      = stepMs;
      adv[F("step-size")]          = stepSize;
      adv[F("end-pause")]          = endPauseMs;
      adv[F("sync-while-dimming")] = syncDimming;
    }

    bool readFromConfig(JsonObject& root) override {
      JsonObject top = root[FPSTR(_name)];
      bool ok = !top.isNull();
      const uint8_t oldBtn = btn;

      ok &= getJsonValue(top[F("enabled")], enabled);
      ok &= getJsonValue(top[F("button")], btn);
      ok &= getJsonValue(top[F("level")], level);
      for (unsigned i = 0; i < BUTTON_DIMMER_MAX_CLICKS; i++) ok &= slotFromJson(top, clickKey(i+1), clickSlot[i], false);
      ok &= slotFromJson(top, F("hold"), holdSlot, true);
      JsonObject dim = top[F("dimming")];
      ok &= getJsonValue(dim[F("min-brightness")], minBri);
      ok &= getJsonValue(dim[F("max-brightness")], maxBri);
      ok &= getJsonValue(dim[F("turn-around")], turnAround);
      JsonObject adv = top[F("advanced")];
      ok &= getJsonValue(adv[F("debounce")], debounceMs);
      ok &= getJsonValue(adv[F("hold-time")], holdMs);
      ok &= getJsonValue(adv[F("multi-click-gap")], clickGapMs);
      ok &= getJsonValue(adv[F("step-interval")], stepMs);
      ok &= getJsonValue(adv[F("step-size")], stepSize);
      ok &= getJsonValue(adv[F("end-pause")], endPauseMs);
      ok &= getJsonValue(adv[F("sync-while-dimming")], syncDimming);

      // keep everything in a usable range
      if (btn >= WLED_MAX_BUTTONS) btn = 0;
      if (level > 2) level = 2;
      if (minBri < 1) minBri = 1;
      if (maxBri <= minBri) maxBri = 255;
      if (minBri >= maxBri) minBri = 1;
      if (stepSize < 1) stepSize = 1;
      if (stepMs < 5) stepMs = 5;
      if (holdMs < 100) holdMs = 100;
      if (debounceMs >= holdMs) debounceMs = holdMs / 2;

      maxClicks = 0;
      for (unsigned i = 0; i < BUTTON_DIMMER_MAX_CLICKS; i++) if (clickSlot[i].action != ACT_NONE) maxClicks = i + 1;
      if (!enabled || btn != oldBtn) {  // the button is handed back: finish the gesture in progress
        if (holding) stopHold();        // publishes the final level if a ramp was running
        pressed = false;
      }
      clicks = 0;
      return ok;
    }

    // adds the drop-downs and the easy / medium / expert filter to the usermod settings page
    void appendConfigData(Print& s) override {
      // B: [button index, label]   L: lowest level at which each block of the page is shown (in page order)
      s.print(F("try{(function(){const B=["));
      bool found = false;
      for (unsigned i = 0; i < buttons.size(); i++) {
        if (buttons[i].pin < 0) continue;
        const uint8_t t = buttons[i].type;
        const bool usable = (t == BTN_TYPE_PUSH || t == BTN_TYPE_PUSH_ACT_HIGH || t == BTN_TYPE_TOUCH);
        s.printf_P(PSTR("[%u,'%u (GPIO %d)%s'],"), i, i, (int)buttons[i].pin, usable ? "" : " - not a push button");
        if (i == btn) found = true;
      }
      if (!found) s.printf_P(PSTR("[%u,'%u (not configured)']"), (unsigned)btn, (unsigned)btn);
      s.print(F("],L=[0,")); // the block of top-level settings is always shown
      for (unsigned i = 0; i < BUTTON_DIMMER_MAX_CLICKS; i++) s.print(i < 2 ? F("0,") : F("1,"));
      s.print(F("0,1,2],")); // hold, dimming, advanced
      s.print(F(
        "P='ButtonDimmer',"
        "A=['None','Toggle on/off','On','Off','Full brightness','Set brightness','Preset','Colour','Random colour','Dim while held'].map((t,i)=>[i,t]),"
        "H={5:'1-255',6:'preset ID',7:'RRGGBB'},"
        "e=gN(P+':enabled');"
        "if(!e)return;"
        "const sec=e.parentNode,"
        "U=()=>{"
          "let l=+d.getElementsByName(P+':level')[1].value;"
          // the AP mode / factory reset warning only applies to button 0
          "let w=gId('bdw');if(w)w.style.display=d.getElementsByName(P+':button')[1].value==0?'':'none';"
          "sec.querySelectorAll('span[data-l]').forEach(g=>g.style.display=+g.dataset.l>l?'none':'');"
          "sec.querySelectorAll('select[name$=\":action\"]').forEach(a=>{"
            "let v=d.getElementsByName(a.name.replace(/action$/,'value'))[1],h=H[a.value];"
            "if(v){v.placeholder=h||'';v.style.width='90px';v.style.opacity=h?1:.3}"
          "})"
        "},"
        "D=(u,f,o)=>{let x=addDD(u,f);if(x){o.forEach(t=>addO(x,t[1],t[0]));x.onchange=U}};"
        // wrap every settings group (from its separator to the next one) so it can be hidden as a whole
        "[...sec.querySelectorAll('hr.sml')].forEach((h,i)=>{"
          "let g=cE('span'),n=h;g.dataset.l=L[i];h.before(g);"
          "do{let x=n.nextSibling;g.append(n);n=x}while(n&&n.tagName!='HR')"
        "});"
        "D(P,'button',B);"
        "addI(P+':button',1,'<i id=\"bdw\" class=\"warn\">hold for AP mode / factory reset is not available on this button</i>');"
        "D(P,'level',[[0,'Easy'],[1,'Medium'],[2,'Expert']]);"
        "for(let i=1;i<L.length-3;i++)D(P+':click-'+i,'action',A.slice(0,-1));"
        "D(P+':hold','action',A);"
        "['debounce','hold-time','multi-click-gap','step-interval','end-pause'].forEach(f=>addI(P+':advanced:'+f,1,'ms'));"
        "addI(P+':level',1,'<i>only changes which settings are shown</i>');"
        "U()"
        "})()}catch(e){console.log(e)}"
      ));
    }
};

